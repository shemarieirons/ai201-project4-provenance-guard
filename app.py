# ---------------------------------------------------------------- routes
@app.route("/submit", methods=["POST"])
@limiter.limit(SUBMIT_LIMIT)
def submit():
    data = request.get_json(silent=True) or {}
    text = data.get("text")
    creator_id = data.get("creator_id")

    if not text or not creator_id:
        return jsonify({"error": "Both 'text' and 'creator_id' are required."}), 400
    word_count = len(text.split())
    if word_count < MIN_WORDS:
        return jsonify({"error": f"Text must be at least {MIN_WORDS} words."}), 400

    content_id = str(uuid.uuid4())
    llm_score, llm_reasoning = llm_signal(text)
    stylo_score, _sd = stylometric_signal(text)
    pattern_score, _pd = pattern_signal(text)
    ai_score, confidence, attribution, notes = score(
        llm_score, stylo_score, pattern_score, word_count
    )

    label = generate_label(attribution)
    status = "classified"

    log_event(
        {
            "content_id": content_id,
            "creator_id": creator_id,
            "event_type": "submission",
            "text": text,
            "attribution": attribution,
            "ai_score": ai_score,
            "confidence": confidence,
            "llm_score": llm_score,
            "stylo_score": stylo_score,
            "pattern_score": pattern_score,
            "llm_reasoning": llm_reasoning,
            "status": status,
            "notes": notes,
        }
    )

    return jsonify(
        {
            "content_id": content_id,
            "creator_id": creator_id,
            "attribution": attribution,
            "ai_score": ai_score,
            "confidence": confidence,
            "signals": {
                "llm_score": llm_score,
                "stylo_score": stylo_score,
                "pattern_score": pattern_score,
            },
            "label": label,
            "status": status,
        }
    )


@app.route("/appeal", methods=["POST"])
@limiter.limit(APPEAL_LIMIT)
def appeal():
    data = request.get_json(silent=True) or {}
    content_id = data.get("content_id")
    creator_id = data.get("creator_id")
    reasoning = data.get("creator_reasoning")

    if not content_id or not creator_id or not isinstance(reasoning, str) or not reasoning.strip():
        return jsonify(
            {"error": "'content_id', 'creator_id', and a non-empty 'creator_reasoning' are required."}
        ), 400
    if len(reasoning) > MAX_REASONING_CHARS:
        return jsonify({"error": f"'creator_reasoning' must be {MAX_REASONING_CHARS} characters or fewer."}), 400

    original = get_submission(content_id)
    if original is None:
        return jsonify({"error": "Unknown content_id."}), 404
    if original["creator_id"] != creator_id:
        return jsonify({"error": "creator_id does not match the original submission."}), 403
    if original["status"] == "under_review":
        return jsonify({"error": "This content is already under review."}), 409

    appeal_ts = datetime.now(timezone.utc).isoformat()
    reasoning = reasoning.strip()

    # 1. Update the original record's status (scores are not touched)
    mark_under_review(content_id, reasoning, appeal_ts)

    # 2. Append a separate appeal event that repeats the original decision
    log_event(
        {
            "content_id": content_id,
            "creator_id": creator_id,
            "event_type": "appeal",
            "text": original["text"],
            "attribution": original["attribution"],
            "ai_score": original["ai_score"],
            "confidence": original["confidence"],
            "llm_score": original["llm_score"],
            "stylo_score": original["stylo_score"],
            "pattern_score": original["pattern_score"],
            "llm_reasoning": original["llm_reasoning"],
            "status": "under_review",
            "appeal_reasoning": reasoning,
            "appeal_timestamp": appeal_ts,
            "notes": original["notes"],
        }
    )

    return jsonify(
        {
            "content_id": content_id,
            "status": "under_review",
            "message": "Appeal received. A person will review this classification.",
            "display_note": "Show this content with its existing label plus a note that it is under review.",
        }
    )


