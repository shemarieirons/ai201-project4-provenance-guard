# ---------------------------------------------------------------- audit log
def init_db():
    with sqlite3.connect(DB_PATH) as conn:
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS audit_log (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                content_id TEXT,
                creator_id TEXT,
                timestamp TEXT,
                event_type TEXT,
                text TEXT,
                attribution TEXT,
                ai_score REAL,
                confidence REAL,
                llm_score REAL,
                stylo_score REAL,
                pattern_score REAL,
                llm_reasoning TEXT,
                status TEXT,
                appeal_reasoning TEXT,
                appeal_timestamp TEXT,
                notes TEXT
            )
            """
        )
        # Migrate an older database that has no pattern_score column
        cols = [r[1] for r in conn.execute("PRAGMA table_info(audit_log)")]
        if "pattern_score" not in cols:
            conn.execute("ALTER TABLE audit_log ADD COLUMN pattern_score REAL")


def log_event(entry):
    fields = [
        "content_id", "creator_id", "event_type", "text", "attribution",
        "ai_score", "confidence", "llm_score", "stylo_score", "pattern_score",
        "llm_reasoning", "status", "appeal_reasoning", "appeal_timestamp", "notes",
    ]
    row = {f: entry.get(f) for f in fields}
    row["timestamp"] = datetime.now(timezone.utc).isoformat()
    cols = ["timestamp"] + fields
    placeholders = ", ".join(":" + c for c in cols)
    with sqlite3.connect(DB_PATH) as conn:
        conn.execute(
            f"INSERT INTO audit_log ({', '.join(cols)}) VALUES ({placeholders})", row
        )


def read_log(limit=50):
    with sqlite3.connect(DB_PATH) as conn:
        conn.row_factory = sqlite3.Row
        rows = conn.execute(
            "SELECT * FROM audit_log ORDER BY id DESC LIMIT ?", (limit,)
        ).fetchall()
    return [dict(r) for r in rows]


def get_submission(content_id):
    """Return the original submission row for a content_id, or None."""
    with sqlite3.connect(DB_PATH) as conn:
        conn.row_factory = sqlite3.Row
        row = conn.execute(
            "SELECT * FROM audit_log WHERE content_id = ? AND event_type = 'submission'",
            (content_id,),
        ).fetchone()
    return dict(row) if row else None


def mark_under_review(content_id, reasoning, appeal_ts):
    """Update the original submission row. Scores are never touched."""
    with sqlite3.connect(DB_PATH) as conn:
        conn.execute(
            "UPDATE audit_log SET status = 'under_review', appeal_reasoning = ?, "
            "appeal_timestamp = ? WHERE content_id = ? AND event_type = 'submission'",
            (reasoning, appeal_ts, content_id),
        )


# ---------------------------------------------------------------- signal 1
def llm_signal(text):
    """Ask Groq how AI-like the text is.

    Returns (score, reasoning). score is a float in [0, 1] (1 = AI-like).
    On any failure returns (None, None), never raises.
    """
    try:
        client = Groq(api_key=os.getenv("GROQ_API_KEY"))
        resp = client.chat.completions.create(
            model=MODEL,
            temperature=0,
            messages=[
                {"role": "system", "content": LLM_PROMPT},
                {"role": "user", "content": text},
            ],
        )
        raw = resp.choices[0].message.content.strip()
        raw = re.sub(r"^```(?:json)?\s*|\s*```$", "", raw).strip()
        data = json.loads(raw)
        score = max(0.0, min(1.0, float(data["ai_probability"])))
        reasoning = str(data.get("reasoning", ""))[:500]
        return score, reasoning
    except Exception as exc:  # noqa: BLE001
        print(f"llm_signal failed: {exc}")
        return None, None


# ---------------------------------------------------------------- helpers
def _clamp(x):
    return max(0.0, min(1.0, x))


def _split_sentences(text):
    """Split on . ! ? followed by space, and on line breaks (so poems work by line)."""
    return [s.strip() for s in re.split(r"[.!?]+\s+|\n+", text.strip()) if s.strip()]


# ---------------------------------------------------------------- signal 2
def stylometric_signal(text):
    """Pure-Python stylometrics. Returns (stylo_score, details).

    stylo_score is in [0, 1] where 1 = AI-like. It is the equal-weight average
    of three metrics, each normalized with the ranges in planning.md.
    """
    words = text.split()
    n_words = max(len(words), 1)

    # Metric 1: sentence length variation (coefficient of variation)
    sentences = _split_sentences(text)
    lengths = [len(s.split()) for s in sentences]
    if len(lengths) >= 2 and statistics.mean(lengths) > 0:
        cv = statistics.pstdev(lengths) / statistics.mean(lengths)
        m1 = _clamp((0.70 - cv) / (0.70 - 0.25))  # cv>=0.70 -> 0, cv<=0.25 -> 1
    else:
        cv = None
        m1 = 0.5  # one sentence: no evidence either way

    # Metric 2: informality and punctuation variety (markers per 100 words)
    dash_chars = ["\u2014", "\u2013", "--"]
    markers = text.count("!") + text.count("?") + text.count("(")
    markers += text.count("...") + text.count("\u2026")
    markers += sum(text.count(d) for d in dash_chars)
    markers += sum(1 for s in sentences if s[:1].islower())
    markers += sum(1 for w in words if len(w) >= 3 and w.isalpha() and w.isupper())
    informal_per_100 = markers / n_words * 100
    m2 = _clamp(1 - informal_per_100 / 4)  # 0 -> 1.0, >=4 per 100 -> 0.0

    # Metric 3: formulaic phrase density (hits per 100 words)
    lowered = text.lower()
    hits = sum(lowered.count(p) for p in FORMULAIC_PHRASES)
    phrases_per_100 = hits / n_words * 100
    m3 = _clamp(phrases_per_100 / 3)  # 0 -> 0.0, >=3 per 100 -> 1.0

    stylo = (m1 + m2 + m3) / 3
    details = {
        "sentence_cv": None if cv is None else round(cv, 3),
        "informal_per_100": round(informal_per_100, 2),
        "phrases_per_100": round(phrases_per_100, 2),
        "m1": round(m1, 3), "m2": round(m2, 3), "m3": round(m3, 3),
    }
    return round(stylo, 3), details


# ---------------------------------------------------------------- signal 3
def pattern_signal(text):
    """Pattern and vocabulary signal (Stretch 1). Returns (pattern_score, details).

    pattern_score is in [0, 1] where 1 = AI-like: the average of
    sentence opener repetition and long-word rate.
    """
    words = text.split()
    n_words = max(len(words), 1)

    # Metric 1: sentence opener repetition (needs at least 3 sentences)
    sentences = _split_sentences(text)
    if len(sentences) >= 3:
        seen = set()
        repeated = 0
        for s in sentences:
            first = re.sub(r"[^a-z]", "", s.split()[0].lower())
            if first in seen:
                repeated += 1
            seen.add(first)
        repeat_share = repeated / len(sentences)
        m1 = _clamp(repeat_share / 0.5)  # 0 -> 0.0, >=50 percent -> 1.0
    else:
        repeat_share = None
        m1 = 0.5  # too few sentences: no evidence either way

    # Metric 2: long-word rate (words with 9+ letters per 100 words)
    long_words = sum(1 for w in words if len(re.sub(r"[^A-Za-z]", "", w)) >= 9)
    long_per_100 = long_words / n_words * 100
    m2 = _clamp((long_per_100 - 4) / (12 - 4))  # <=4 -> 0.0, >=12 -> 1.0

    pattern = (m1 + m2) / 2
    details = {
        "opener_repeat_share": None if repeat_share is None else round(repeat_share, 3),
        "long_words_per_100": round(long_per_100, 2),
        "m1": round(m1, 3), "m2": round(m2, 3),
    }
    return round(pattern, 3), details


# ---------------------------------------------------------------- scoring
def score(llm, stylo, pattern, word_count):
    """Combine all three signals.

    Returns (ai_score, confidence, attribution, notes).
    """
    # LLM failed: never make a confident call without it
    if llm is None:
        return 0.5, 1.0, "uncertain", "llm_unavailable"

    notes = []
    if word_count < SHORT_TEXT_WORDS:
        w_llm, w_stylo, w_pattern = WEIGHTS_SHORT
        notes.append("short_text_weights")
    else:
        w_llm, w_stylo, w_pattern = WEIGHTS
    base = w_llm * llm + w_stylo * stylo + w_pattern * pattern

    spread = max(llm, stylo, pattern) - min(llm, stylo, pattern)
    if spread > DISAGREE_LIMIT:
        ai_score = 0.5 + (base - 0.5) * 0.5
        notes.append("signals_disagree")
    else:
        ai_score = base
    ai_score = round(ai_score, 3)

    # Attribution with the agreement guard on the AI label
    guard_ok = llm >= GUARD_LLM and stylo >= GUARD_STYLO and pattern >= GUARD_PATTERN
    if ai_score >= AI_THRESHOLD and guard_ok:
        attribution = "likely_ai"
        confidence = ai_score
    elif ai_score <= HUMAN_THRESHOLD:
        attribution = "likely_human"
        confidence = 1 - ai_score
    else:
        attribution = "uncertain"
        confidence = 1 - 2 * abs(ai_score - 0.5)
        if ai_score >= AI_THRESHOLD:
            notes.append("ai_guard_downgrade")

    return ai_score, round(confidence, 3), attribution, ",".join(notes) or None


