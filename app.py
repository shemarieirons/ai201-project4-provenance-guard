import json
import os
import re
import sqlite3
import statistics
import uuid
from datetime import datetime, timezone

from dotenv import load_dotenv
from flask import Flask, jsonify, request
from groq import Groq

load_dotenv()

app = Flask(__name__)

DB_PATH = "audit_log.db"
MODEL = os.getenv("GROQ_MODEL", "openai/gpt-oss-20b")
MIN_WORDS = 10

# ---- scoring constants (all from planning.md sections 1 and 2) ----
SHORT_TEXT_WORDS = 40
W_LLM, W_STYLO = 0.60, 0.40
W_LLM_SHORT, W_STYLO_SHORT = 0.75, 0.25
DISAGREE_LIMIT = 0.40
AI_THRESHOLD = 0.80
HUMAN_THRESHOLD = 0.35
GUARD_MIN = 0.60  # both signals must be at least this for likely_ai

LLM_PROMPT = (
    "You are assessing whether a piece of writing was generated by AI or written "
    "by a human. Consider generic phrasing, cautious or balanced tone, lack of "
    "specific personal detail, overly smooth transitions, and repetitive structure. "
    "Respond with ONLY a JSON object, no other text, in this exact form: "
    '{"ai_probability": <number from 0 to 1>, "reasoning": "<one sentence>"}. '
    "0 means clearly human-written and 1 means clearly AI-generated."
)

FORMULAIC_PHRASES = [
    "it is important to note", "it is worth noting", "furthermore", "moreover",
    "in conclusion", "additionally", "delve", "tapestry", "paradigm",
    "plays a crucial role", "stakeholders", "landscape", "transformative",
    "multifaceted", "ever-evolving", "in today's", "navigate the",
]


# ---------------------------------------------------------------- audit log
def init_db():
    with sqlite3.connect(DB_PATH) as conn:
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS audit_log (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                content_id TEXT,
                creator_id TEXT,
                timestamp TEXT,
                event_type TEXT,
                text TEXT,
                attribution TEXT,
                ai_score REAL,
                confidence REAL,
                llm_score REAL,
                stylo_score REAL,
                llm_reasoning TEXT,
                status TEXT,
                appeal_reasoning TEXT,
                appeal_timestamp TEXT,
                notes TEXT
            )
            """
        )


def log_event(entry):
    fields = [
        "content_id", "creator_id", "event_type", "text", "attribution",
        "ai_score", "confidence", "llm_score", "stylo_score", "llm_reasoning",
        "status", "appeal_reasoning", "appeal_timestamp", "notes",
    ]
    row = {f: entry.get(f) for f in fields}
    row["timestamp"] = datetime.now(timezone.utc).isoformat()
    cols = ["timestamp"] + fields
    placeholders = ", ".join(":" + c for c in cols)
    with sqlite3.connect(DB_PATH) as conn:
        conn.execute(
            f"INSERT INTO audit_log ({', '.join(cols)}) VALUES ({placeholders})", row
        )


def read_log(limit=50):
    with sqlite3.connect(DB_PATH) as conn:
        conn.row_factory = sqlite3.Row
        rows = conn.execute(
            "SELECT * FROM audit_log ORDER BY id DESC LIMIT ?", (limit,)
        ).fetchall()
    return [dict(r) for r in rows]


# ---------------------------------------------------------------- signal 1
def llm_signal(text):
    """Ask Groq how AI-like the text is.

    Returns (score, reasoning). score is a float in [0, 1] (1 = AI-like).
    On any failure returns (None, None), never raises.
    """
    try:
        client = Groq(api_key=os.getenv("GROQ_API_KEY"))
        resp = client.chat.completions.create(
            model=MODEL,
            temperature=0,
            messages=[
                {"role": "system", "content": LLM_PROMPT},
                {"role": "user", "content": text},
            ],
        )
        raw = resp.choices[0].message.content.strip()
        raw = re.sub(r"^```(?:json)?\s*|\s*```$", "", raw).strip()
        data = json.loads(raw)
        score = max(0.0, min(1.0, float(data["ai_probability"])))
        reasoning = str(data.get("reasoning", ""))[:500]
        return score, reasoning
    except Exception as exc:  # noqa: BLE001
        print(f"llm_signal failed: {exc}")
        return None, None


# ---------------------------------------------------------------- signal 2
def _clamp(x):
    return max(0.0, min(1.0, x))


def stylometric_signal(text):
    """Pure-Python stylometrics. Returns (stylo_score, details).

    stylo_score is in [0, 1] where 1 = AI-like. It is the equal-weight average
    of three metrics, each normalized with the ranges in planning.md.
    """
    words = text.split()
    n_words = max(len(words), 1)

    # Metric 1: sentence length variation (coefficient of variation)
    sentences = [s.strip() for s in re.split(r"[.!?]+\s+|\n+", text.strip()) if s.strip()]
    lengths = [len(s.split()) for s in sentences]
    if len(lengths) >= 2 and statistics.mean(lengths) > 0:
        cv = statistics.pstdev(lengths) / statistics.mean(lengths)
        m1 = _clamp((0.70 - cv) / (0.70 - 0.25))  # cv>=0.70 -> 0, cv<=0.25 -> 1
    else:
        cv = None
        m1 = 0.5  # one sentence: no evidence either way

    # Metric 2: informality and punctuation variety (markers per 100 words)
    dash_chars = ["\u2014", "\u2013", "--"]
    markers = text.count("!") + text.count("?") + text.count("(")
    markers += text.count("...") + text.count("\u2026")
    markers += sum(text.count(d) for d in dash_chars)
    markers += sum(1 for s in sentences if s[:1].islower())
    markers += sum(1 for w in words if len(w) >= 3 and w.isalpha() and w.isupper())
    informal_per_100 = markers / n_words * 100
    m2 = _clamp(1 - informal_per_100 / 4)  # 0 -> 1.0, >=4 per 100 -> 0.0

    # Metric 3: formulaic phrase density (hits per 100 words)
    lowered = text.lower()
    hits = sum(lowered.count(p) for p in FORMULAIC_PHRASES)
    phrases_per_100 = hits / n_words * 100
    m3 = _clamp(phrases_per_100 / 3)  # 0 -> 0.0, >=3 per 100 -> 1.0

    stylo = (m1 + m2 + m3) / 3
    details = {
        "sentence_cv": None if cv is None else round(cv, 3),
        "informal_per_100": round(informal_per_100, 2),
        "phrases_per_100": round(phrases_per_100, 2),
        "m1": round(m1, 3), "m2": round(m2, 3), "m3": round(m3, 3),
    }
    return round(stylo, 3), details


# ---------------------------------------------------------------- scoring
def score(llm, stylo, word_count):
    """Combine both signals. Returns (ai_score, confidence, attribution, notes)."""
    # LLM failed: never make a confident call without it
    if llm is None:
        return 0.5, 1.0, "uncertain", "llm_unavailable"

    notes = []
    if word_count < SHORT_TEXT_WORDS:
        base = W_LLM_SHORT * llm + W_STYLO_SHORT * stylo
        notes.append("short_text_weights")
    else:
        base = W_LLM * llm + W_STYLO * stylo

    if abs(llm - stylo) > DISAGREE_LIMIT:
        ai_score = 0.5 + (base - 0.5) * 0.5
        notes.append("signals_disagree")
    else:
        ai_score = base
    ai_score = round(ai_score, 3)

    # Attribution with the agreement guard on the AI label
    if ai_score >= AI_THRESHOLD and llm >= GUARD_MIN and stylo >= GUARD_MIN:
        attribution = "likely_ai"
        confidence = ai_score
    elif ai_score <= HUMAN_THRESHOLD:
        attribution = "likely_human"
        confidence = 1 - ai_score
    else:
        attribution = "uncertain"
        confidence = 1 - 2 * abs(ai_score - 0.5)
        if ai_score >= AI_THRESHOLD:
            notes.append("ai_guard_downgrade")

    return ai_score, round(confidence, 3), attribution, ",".join(notes) or None


# ---------------------------------------------------------------- routes
@app.route("/submit", methods=["POST"])
def submit():
    data = request.get_json(silent=True) or {}
    text = data.get("text")
    creator_id = data.get("creator_id")

    if not text or not creator_id:
        return jsonify({"error": "Both 'text' and 'creator_id' are required."}), 400
    word_count = len(text.split())
    if word_count < MIN_WORDS:
        return jsonify({"error": f"Text must be at least {MIN_WORDS} words."}), 400

    content_id = str(uuid.uuid4())
    llm_score, llm_reasoning = llm_signal(text)
    stylo_score, _details = stylometric_signal(text)
    ai_score, confidence, attribution, notes = score(llm_score, stylo_score, word_count)

    label = f"Placeholder label for '{attribution}' (real labels arrive in Milestone 5)."
    status = "classified"

    log_event(
        {
            "content_id": content_id,
            "creator_id": creator_id,
            "event_type": "submission",
            "text": text,
            "attribution": attribution,
            "ai_score": ai_score,
            "confidence": confidence,
            "llm_score": llm_score,
            "stylo_score": stylo_score,
            "llm_reasoning": llm_reasoning,
            "status": status,
            "notes": notes,
        }
    )

    return jsonify(
        {
            "content_id": content_id,
            "creator_id": creator_id,
            "attribution": attribution,
            "ai_score": ai_score,
            "confidence": confidence,
            "signals": {"llm_score": llm_score, "stylo_score": stylo_score},
            "label": label,
            "status": status,
        }
    )


@app.route("/log", methods=["GET"])
def view_log():
    limit = request.args.get("limit", default=50, type=int)
    return jsonify({"entries": read_log(limit)})


